import math, sys, os
out = sys.argv[1]
def f(v): return f"{v:.2f}"
def poly(pts): return "M" + " L".join(f"{f(x)},{f(y)}" for x,y in pts)
k = math.log(3) / (2*math.pi); rot = math.radians(-35)
def raw(th):
    r = math.exp(k*th); return (r*math.cos(th+rot), r*math.sin(th+rot))
outer_raw = [raw(-2*math.pi + 2*math.pi*i/200) for i in range(201)]

def geometry(view, size, every=1):
    xs = [p[0] for p in outer_raw]; ys = [p[1] for p in outer_raw]
    sc = size / max(max(xs)-min(xs), max(ys)-min(ys))
    ox = view/2 - sc*(max(xs)+min(xs))/2; oy = view/2 - sc*(max(ys)+min(ys))/2
    T = lambda p: (ox + sc*p[0], oy + sc*p[1])
    shell = poly([T(p) for p in outer_raw]) + " Z"
    inner = poly([T(raw(-2*math.pi - 4*math.pi*(1 - i/300))) for i in range(301)])
    septa = []; th = -math.radians(40); n = 0
    while th > -5*math.pi:
        a = T(raw(th)); b = T(raw(th - 2*math.pi))
        m = T(raw(th - math.radians(14))); mi = T(raw(th - 2*math.pi - math.radians(14)))
        c = ((m[0]+mi[0])/2, (m[1]+mi[1])/2)
        if math.dist(a, b) > 3.5 * view / 108 * (2 if every > 1 else 1) and n % every == 0:
            septa.append(f"M{f(b[0])},{f(b[1])} Q{f(c[0])},{f(c[1])} {f(a[0])},{f(a[1])}")
        th -= math.radians(34); n += 1
    lo = min(T(p)[1] for p in outer_raw); hi = max(T(p)[1] for p in outer_raw)
    return shell, inner, " ".join(septa), lo, hi

def head(view, dp):
    return f'''<?xml version="1.0" encoding="utf-8"?>
<!-- Kabuk = shell: a nautilus cross-section. Generated by scripts/logo.py -->
<vector xmlns:android="http://schemas.android.com/apk/res/android" xmlns:aapt="http://schemas.android.com/aapt"
    android:width="{dp}dp" android:height="{dp}dp" android:viewportWidth="{view}" android:viewportHeight="{view}">
'''
def grad(x1,y1,x2,y2,c1,c2):
    return f'''        <aapt:attr name="android:fillColor">
            <gradient android:type="linear" android:startX="{x1:.1f}" android:startY="{y1:.1f}" android:endX="{x2:.1f}" android:endY="{y2:.1f}"
                android:startColor="{c1}" android:endColor="{c2}" />
        </aapt:attr>
'''
def w(name, s): open(os.path.join(out, name + ".xml"), "w").write(s)

shell, inner, septa, lo, hi = geometry(108, 58)
line = '#55301020'
w("ic_launcher_fg", head(108, 108) + f'    <path android:pathData="{shell}">\n' + grad(30, lo, 80, hi, "#FFFFC48A", "#FFF7768E") + '    </path>\n'
  + f'    <path android:strokeColor="{line}" android:strokeWidth="1.8" android:strokeLineCap="round" android:pathData="{septa}" />\n'
  + f'    <path android:strokeColor="{line}" android:strokeWidth="2.2" android:strokeLineCap="round" android:pathData="{inner}" />\n</vector>\n')
w("ic_launcher_bg", head(108, 108) + '    <path android:pathData="M0,0h108v108h-108z">\n' + grad(0, 0, 108, 108, "#FF1B2133", "#FF0B0E14") + '    </path>\n</vector>\n')
# themed icons (Android 13+) and notifications: line art in one colour
def mono(view, dp, size, sw, every):
    shell, inner, septa, _, _ = geometry(view, size, every)
    return head(view, dp) + f'''    <path android:strokeColor="#FFFFFFFF" android:strokeWidth="{sw*1.4:.2f}" android:strokeLineJoin="round" android:pathData="{shell}" />
    <path android:strokeColor="#FFFFFFFF" android:strokeWidth="{sw*0.8:.2f}" android:strokeLineCap="round" android:pathData="{septa}" />
    <path android:strokeColor="#FFFFFFFF" android:strokeWidth="{sw:.2f}" android:strokeLineCap="round" android:pathData="{inner}" />
</vector>
'''
w("ic_launcher_mono", mono(108, 108, 54, 2.6, 1))
w("ic_notification", mono(24, 24, 20, 1.1, 2))
